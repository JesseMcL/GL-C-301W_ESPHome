"""Generate host-integration.yaml from ../gl-c-301w.yaml for run.sh.

The device YAML is used as is, minus the BK7238 / network blocks, with the
MCU UART on a pty and a test sequence in on_boot. Text-based on purpose:
top-level blocks are cut by name, so keep the device YAML's top-level keys
unindented and its blocks contiguous.
"""
import re
import sys

DROP = {"bk72xx", "api", "ota", "wifi", "captive_portal", "sensor", "logger",
        "external_components"}

TEST_BOOT = """\
  on_boot:
    priority: -100
    then:
      - delay: 3s
      - logger.log: "TEST: light on"
      - light.turn_on: {id: rgbcw_light, brightness: 100%, color_temperature: 2700 K, transition_length: 1s}
      - delay: 2s
      - logger.log: "TEST: starting MCU update"
      - update.perform: mcu_update
      - delay: 25s
      - logger.log: "TEST: light after update"
      - light.turn_on: {id: rgbcw_light, brightness: 50%, color_temperature: 6500 K, transition_length: 0s}
"""

TAIL = """
# ---- host test additions ----
host:

external_components:
  - source:
      type: local
      path: ../components
    components: [tuya_mcu]

logger:
  level: DEBUG
  logs:
    tuya: INFO
    binary_sensor: INFO
    script: INFO
"""


def blocks(text):
    """Split into (key, lines) per top-level block; comments stay with the
    block that follows them."""
    out, cur, key, pending = [], [], None, []
    for line in text.splitlines(keepends=True):
        m = re.match(r"([a-z_0-9]+):", line)
        if m:
            if cur or key:
                out.append((key, cur))
            key, cur = m.group(1), pending + [line]
            pending = []
        elif line.startswith("#") or not line.strip():
            pending.append(line)
        else:
            cur += pending + [line]
            pending = []
    out.append((key, cur + pending))
    return out


def main(src, dst):
    res = ["# GENERATED by make_host_yaml.py from %s - do not edit\n" % src]
    for key, lines in blocks(open(src).read()):
        if key in DROP:
            continue
        text = "".join(lines)
        if key == "substitutions":
            text = re.sub(r"(?m)^  name: .*$", "  name: gl-c-301w-host-test", text)
            text = re.sub(r"(?m)^  mcu_firmware: .*$", "  mcu_firmware: ../../mcu/dist/manifest.json", text)
        elif key == "esphome":
            text = text.rstrip("\n") + "\n" + TEST_BOOT + "\n"
        elif key == "uart":
            text = re.sub(r"(?m)^  (tx|rx)_pin: .*\n", "", text)
            text = text.replace("  id: mcu_uart\n", "  id: mcu_uart\n  port: /tmp/esptty\n")
        res.append(text)
    res.append(TAIL)
    open(dst, "w").write("".join(res))


if __name__ == "__main__":
    main(*sys.argv[1:3])
